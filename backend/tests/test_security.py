def test_secure_paste_ids_entropy_and_unpredictability():
    """
    Verify paste IDs generated by secrets.token_urlsafe have sufficient entropy,
    are non-sequential, URL-safe, and hard to guess.
    """
    ids = set()
    for _ in range(100):
        pid = generate_paste_id(8)
        assert len(pid) >= 10  # 8 bytes base64url encoded is 11 chars
        assert pid not in ids  # No collisions in small sample
        ids.add(pid)


def test_id_collision_never_overwrites_existing_record(test_db: Path):
    """
    Verify that if an ID collision occurs, create_paste does not overwrite the existing record
    and retries until a unique ID is found.
    """
    # 1. Create initial paste with a fixed ID
    first_paste = create_paste(
        content="First original paste content",
        db_path=test_db,
        id_generator=lambda: "fixed_test_id",
        max_retries=1,
    )
    assert first_paste["id"] == "fixed_test_id"

    # 2. Sequence generator: first yields collision "fixed_test_id", then "unique_new_id"
    sequence = ["fixed_test_id", "unique_new_id"]
    second_paste = create_paste(
        content="Second new paste content",
        db_path=test_db,
        id_generator=lambda: sequence.pop(0),
        max_retries=3,
    )
    assert second_paste["id"] == "unique_new_id"

    # 3. Verify original paste was NOT overwritten in database
    from paste_repository import get_paste_by_id
    orig = get_paste_by_id("fixed_test_id", db_path=test_db)
    assert orig["content"] == "First original paste content"


def test_server_side_validation_rejects_empty_and_whitespace(client: TestClient):
    """
    Verify server-side validation rejects empty or whitespace-only strings with HTTP 422.
    """
    # Empty string
    r1 = client.post("/pastes", json={"content": "", "expiry_minutes": 10})
    assert r1.status_code == 422

    # Whitespace only
    r2 = client.post("/pastes", json={"content": "    \n\t  ", "expiry_minutes": 10})
    assert r2.status_code == 422


def test_server_side_validation_rejects_invalid_expiry_types(client: TestClient):
    """
    Verify server-side validation rejects booleans, floats, strings, and zero/negative numbers.
    """
    # Booleans
    r_bool = client.post("/pastes", json={"content": "valid", "expiry_minutes": True})
    assert r_bool.status_code == 422

    # Floats
